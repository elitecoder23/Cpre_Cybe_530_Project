#!/usr/bin/env python3
"""Generate the three lab captures and the web page's question data.

    python generate.py                 # default seed 530 -> web/pcaps/*.pcap
    python generate.py --seed 7        # a fresh variant (new hosts, IPs, sizes)
    python generate.py --lab 2         # only one lab

Outputs
    web/pcaps/lab0_tutorial.pcap, lab1_https_beacon.pcap, lab2_dns_tunnel.pcap, lab3_icmp_tunnel.pcap
    web/labdata.js                     questions + hashed answers for the web page
    instructor/ANSWER_KEY.md           plain-text answers and walkthroughs
    instructor/ground_truth.json       raw ground truth from the generators
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from labs import lab0_tutorial, lab1_beacon, lab2_dns, lab3_icmp  # noqa: E402
import questions  # noqa: E402

LABS = {
    0: ("lab0_tutorial.pcap", lab0_tutorial, questions.build_lab0),
    1: ("lab1_https_beacon.pcap", lab1_beacon, questions.build_lab1),
    2: ("lab2_dns_tunnel.pcap", lab2_dns, questions.build_lab2),
    3: ("lab3_icmp_tunnel.pcap", lab3_icmp, questions.build_lab3),
}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seed", type=int, default=530, help="random seed (default 530)")
    ap.add_argument("--lab", choices=["0", "1", "2", "3", "all"], default="all")
    ap.add_argument("--out", default=os.path.join(HERE, "web", "pcaps"), help="PCAP output directory")
    args = ap.parse_args()

    chosen = list(LABS) if args.lab == "all" else [int(args.lab)]
    truth, labs = {}, []
    for n in sorted(LABS):
        fname, mod, builder = LABS[n]
        # Always generate every lab so web/labdata.js stays complete; --lab only limits printing.
        path = os.path.join(args.out, fname)
        truth[n] = mod.generate(path, args.seed)
        labs.append(builder(truth[n], args.seed))
        if n in chosen:
            print("lab %d: wrote %s (%d packets)" % (n, path, truth[n]["packets"]))
    labs.append(questions.build_quiz(args.seed))

    public = json.loads(json.dumps(labs))
    for lab in public:
        for q in lab["questions"]:
            q.pop("_answer", None)
    with open(os.path.join(HERE, "web", "labdata.js"), "w") as f:
        f.write("// Generated by generate.py (seed %d). Do not edit.\nwindow.LABDATA = " % args.seed)
        json.dump(public, f, indent=1)
        f.write(";\n")

    os.makedirs(os.path.join(HERE, "instructor"), exist_ok=True)
    with open(os.path.join(HERE, "instructor", "ground_truth.json"), "w") as f:
        json.dump({"seed": args.seed, "labs": truth}, f, indent=1)
    with open(os.path.join(HERE, "instructor", "ANSWER_KEY.md"), "w") as f:
        f.write("# Answer Key (seed %d)\n\nInstructor copy. Do not publish with the student page.\n" % args.seed)
        for lab in labs:
            f.write("\n## %s\n\n" % lab["title"])
            for i, q in enumerate(lab["questions"], 1):
                f.write("%d. %s\n   - **Answer:** %s\n   - Why: %s\n" % (i, q["prompt"], q["_answer"], q["explain"]))
            if lab["walkthrough"]:
                f.write("\n**Walkthrough**\n\n")
                for line in lab["walkthrough"]:
                    f.write("- %s\n" % line)
    print("wrote web/labdata.js and instructor/ANSWER_KEY.md")


if __name__ == "__main__":
    main()
